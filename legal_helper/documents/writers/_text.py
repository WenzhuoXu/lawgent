_WIDE_RANGES = (
    (0x1100, 0x115F), (0x2E80, 0x303E), (0x3041, 0x33FF), (0x3400, 0x4DBF),
    (0x4E00, 0x9FFF), (0xA000, 0xA4CF), (0xAC00, 0xD7A3), (0xF900, 0xFAFF),
    (0xFE30, 0xFE4F), (0xFF00, 0xFF60), (0xFFE0, 0xFFE6),
    (0x20000, 0x3FFFD),
)


def is_wide(ch: str) -> bool:
    cp = ord(ch)
    return any(lo <= cp <= hi for lo, hi in _WIDE_RANGES)


def display_width(text: str) -> float:
    """Width of ``text`` in ems: a Han glyph is one em, Latin about half."""
    return sum(1.0 if is_wide(c) else 0.5 for c in text or "")


def joined_text(parts: Iterable[Optional[str]]) -> str:
    return "\n".join(p for p in parts if p)


