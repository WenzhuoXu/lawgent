"""Language and text facts shared by the document writers.

Three decisions live here so the Word writer, the PDF writer and the export
path cannot disagree about them:

* **Is this document Chinese?** Decided by the *share* of Han ideographs in
  the content, not by the presence of any CJK character. The old test switched
  an English memo onto Chinese typography (宋体 body, 首行缩进, and now A4 and a
  "第 X 页 共 Y 页" footer) on the strength of one fullwidth comma or one party
  name: 18 of 27 low-Han documents were on the wrong track.
* **What does the disclaimer say?** One text per language. It goes into the
  file's document properties, never into the instrument body — 88 of 104
  Chinese DOCX opened with an English AI disclaimer, including every court
  filing written fresh.
* **What is an exported answer called?** Its own first heading, in its own
  language — not a fixed English "Legal Analysis".

``display_width`` is a copy of :func:`legal_helper.documents.graph_layout.display_width`.
The writers measure table columns and spreadsheet widths with it, and the
diagram module is owned by the deck code, which may move; a ten-line estimator
is cheaper to own than to depend on.
"""

from __future__ import annotations

import re
from typing import Iterable, Literal, Optional

Lang = Literal["zh", "en"]

#: Han ideographs: the URO, extension A, compatibility ideographs, and the
#: supplementary-plane extensions. Kana, Hangul and CJK punctuation are not
#: Han — a fullwidth comma says nothing about the language of a document.
_HAN_RE = re.compile(
    "[㐀-䶿一-鿿豈-﫿\U00020000-\U0003134f]"
)
_LATIN_WORD_RE = re.compile(r"[A-Za-zÀ-ɏ]+(?:['’][A-Za-z]+)?")

#: A document is Chinese when most of its words are. A Han character and a
#: Latin word are the units because they carry about the same amount of text:
#: a bilingual PRC contract (Chinese and English versions side by side) lands
#: near 0.6 and an English memo quoting one Chinese statute title stays near 0.
CHINESE_SHARE_THRESHOLD = 0.5


def han_share(text: str) -> float:
    """Share of Han characters among Han characters plus Latin words."""
    han = len(_HAN_RE.findall(text or ""))
    words = len(_LATIN_WORD_RE.findall(text or ""))
    total = han + words
    return han / total if total else 0.0


def detect_lang(*texts: Optional[str]) -> Lang:
    """``"zh"`` when the joined texts are mostly Chinese, else ``"en"``."""
    joined = "\n".join(t for t in texts if t)
    return "zh" if han_share(joined) >= CHINESE_SHARE_THRESHOLD else "en"


def resolve_lang(lang: Optional[str], *texts: Optional[str]) -> Lang:
    """Normalise an explicit ``lang`` (``zh``, ``zh-CN``, ``en``, ``auto``)."""
    value = (lang or "auto").strip().lower()
    if value in {"", "auto"}:
        return detect_lang(*texts)
    return "zh" if value.startswith("zh") else "en"


def bcp47(lang: Lang) -> str:
    return "zh-CN" if lang == "zh" else "en-US"


#: The not-legal-advice notice, per language. Written to document properties
#: (Word: core ``description``; PDF: ``Subject``), never into the body.
DISCLAIMERS: dict[Lang, str] = {
    "zh": "本文件由法律 AI 助手生成，不构成法律意见；依赖前须经具有相应执业资格的律师审核。",
    "en": (
        "Generated by a legal AI assistant — not legal advice. Must be reviewed by "
        "qualified counsel in the relevant jurisdiction before reliance."
    ),
}


def disclaimer_for(lang: Lang) -> str:
    return DISCLAIMERS[lang]


#: Generic export titles, used only when the answer has no heading and the
#: caller supplied no title.
GENERIC_TITLES: dict[Lang, str] = {"zh": "法律分析", "en": "Legal Analysis"}

_ATX_HEADING_RE = re.compile(r"^\s{0,3}(#{1,6})\s+(.*?)\s*#*\s*$")
_INLINE_MARK_RE = re.compile(r"(\*\*|__|\*|_|`|~~)")
_LINK_RE = re.compile(r"!?\[([^\]]*)\]\([^)]*\)")


def _plain(text: str) -> str:
    text = _LINK_RE.sub(r"\1", text)
    return _INLINE_MARK_RE.sub("", text).strip()


def split_leading_heading(markdown: str) -> tuple[str, str]:
    """``(heading_text, rest)`` when the first non-blank line is a heading.

    Returns ``("", markdown)`` otherwise. Only an ATX heading on the very first
    line counts: a heading further down titles a section, not the document.
    """
    lines = (markdown or "").splitlines()
    for index, line in enumerate(lines):
        if not line.strip():
            continue
        match = _ATX_HEADING_RE.match(line)
        if not match:
            return "", markdown
        heading = _plain(match.group(2))
        if not heading:
            return "", markdown
        rest = "\n".join(lines[index + 1:]).lstrip("\n")
        return heading, rest
    return "", markdown


def export_title(markdown: str, *, chat_title: str = "", lang: Optional[Lang] = None) -> str:
    """Title for an exported answer: its first heading, the chat, or generic.

    The chat title is used only when it is in the answer's language — an
    English chat title on a Chinese answer is the same defect as an English
    "Legal Analysis" on it.
    """
    lang = lang or detect_lang(markdown)
    heading, _ = split_leading_heading(markdown)
    if heading:
        return heading[:120]
    candidate = (chat_title or "").strip()
    if candidate and detect_lang(candidate) == lang and candidate.lower() not in {
        "new chat", "untitled", "新对话", "新聊天",
    }:
        return candidate[:120]
    return GENERIC_TITLES[lang]


def strip_title_heading(markdown: str, title: str) -> str:
    """Drop the answer's leading heading when it is the document title.

    The title page already prints it; leaving it in the body prints it twice.
    """
    heading, rest = split_leading_heading(markdown)
    if heading and heading.strip() == (title or "").strip():
        return rest
    return markdown


# ---------------------------------------------------------------------------
# Width
